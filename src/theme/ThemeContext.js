const THEME_PALETTES = {
  light: BASE_LIGHT,
  dark: BASE_DARK,
  forest: BASE_FOREST,
  ocean: BASE_OCEAN,
  ember: BASE_EMBER,
  midnight: BASE_MIDNIGHT,
  crimson: BASE_CRIMSON,
  aurora: BASE_AURORA,
  candy: BASE_CANDY,
};

export function ThemeProvider({ children, initialTheme = 'dark' }) {
  const [themeId, setThemeId] = useState(initialTheme);
  const [diffAccent, setDiffAccent] = useState(null);

  const setThemeMode = useCallback((nextTheme) => {
    if (THEME_PALETTES[nextTheme]) {
      setThemeId(nextTheme);
    } else {
      setThemeId('light');
    }
  }, []);

  const setDifficultyAccent = useCallback((difficultyKey) => {
    const config = DIFFICULTY[difficultyKey];
    if (config) setDiffAccent(config.color);
    else setDiffAccent(null);
  }, []);

  const baseColors = THEME_PALETTES[themeId] || BASE_LIGHT;
  const isDark = baseColors.mode === 'dark';
  const accent = diffAccent || baseColors.primary;

  const colors = {
    ...baseColors,
    primary: accent,
    primaryDark: accent,
  };

  return (
    <ThemeContext.Provider value={{ theme: themeId, colors, setThemeMode, isDark, setDifficultyAccent, accent }}>
      {children}
    </ThemeContext.Provider>
  );
}

export function useTheme() {
  const ctx = useContext(ThemeContext);
  if (!ctx) throw new Error('useTheme must be used within ThemeProvider');
  return ctx;
}
